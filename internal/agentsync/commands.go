func geminiCommands(env Env, scope Scope, cmds []Command) ([]Op, string) {
	dir := filepath.Join(env.root(scope), ".gemini", "commands")
	var files []ownedFile
	for _, c := range cmds {
		files = append(files, ownedFile{c.Name, geminiCommandTOML(c)})
	}
	return []Op{&ownedFilesOp{meta: meta{Gemini, KindCommands, scope}, dir: dir, ext: ".toml", files: files, mode: 0o644}}, ""
}

func geminiCommandTOML(c Command) []byte {
	prompt := strings.ReplaceAll(strings.TrimSpace(c.Body), "$ARGUMENTS", "{{args}}")
	prompt = strings.ReplaceAll(prompt, `\`, `\\`)
	prompt = strings.ReplaceAll(prompt, `"""`, `""\"`)
	var b strings.Builder
	b.WriteString("# " + Marker + ": generated by `relay sync`, edit the source in the relay sync directory\n")
	if c.Description != "" {
		b.WriteString("description = " + tomlStr(c.Description) + "\n")
	}
	b.WriteString("prompt = \"\"\"\n" + prompt + "\n\"\"\"\n")
	return []byte(b.String())
}
