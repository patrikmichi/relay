package agentsync

import (
	"path/filepath"
	"strings"
)

func commandFrontmatter(c Command, keys ...string) []string {
	var fm []string
	for _, k := range keys {
		switch {
		case k == "description" && c.Description != "":
			fm = append(fm, "description: "+yamlScalar(c.Description))
		case k == "argument-hint" && c.ArgumentHint != "":
			fm = append(fm, "argument-hint: "+yamlScalar(c.ArgumentHint))
		case k == "agent: agent":
			fm = append(fm, k)
		}
	}
	return fm
}

// markdownCommands writes one owned markdown file per command into dir.
func markdownCommands(a AgentID, scope Scope, dir, ext string, cmds []Command, front func(Command) []string, body func(Command) string) []Op {
	var files []ownedFile
	for _, c := range cmds {
		files = append(files, ownedFile{c.Name, ownedMarkdown(front(c), mdMarkerLine, body(c))})
	}
	return []Op{&ownedFilesOp{meta: meta{a, KindCommands, scope}, dir: dir, ext: ext, files: files, mode: 0o644}}
}

func plainBody(c Command) string { return c.Body }

func claudeCommands(env Env, scope Scope, cmds []Command) ([]Op, string) {
	dir := filepath.Join(env.root(scope), ".claude", "commands")
	return markdownCommands(Claude, scope, dir, ".md", cmds, func(c Command) []string {
		return commandFrontmatter(c, "description", "argument-hint")
	}, plainBody), ""
}

