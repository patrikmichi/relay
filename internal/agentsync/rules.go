func cursorRules(env Env, scope Scope, rules []Rule) ([]Op, string) {
	if scope == ScopeUser {
		return nil, "Cursor user rules live in Settings, not in a file relay can manage"
	}
	var files []ownedFile
	for _, r := range rules {
		fm := []string{"description: " + yamlScalar(r.Description)}
		if len(r.Globs) > 0 {
			fm = append(fm, "globs: "+yamlScalar(strings.Join(r.Globs, ",")))
		}
		fm = append(fm, fmt.Sprintf("alwaysApply: %t", r.Always))
		files = append(files, ownedFile{r.Name, ownedMarkdown(fm, mdMarkerLine, r.Body)})
	}
	return []Op{&ownedFilesOp{meta: meta{Cursor, KindRules, scope}, dir: filepath.Join(env.Project, ".cursor", "rules"), ext: ".mdc", files: files, mode: 0o644}}, ""
}

func windsurfRules(env Env, scope Scope, rules []Rule) ([]Op, string) {
	m := meta{Windsurf, KindRules, scope}
	if scope == ScopeUser {
		body := rulesBlock(rules)
		ops := []Op{&mdBlockOp{meta: m, path: filepath.Join(env.Home, ".codeium", "windsurf", "memories", "global_rules.md"), id: "rules", body: body}}
		if len(body) > windsurfGlobalRulesLimit {
			ops = append(ops, noteOp{m.item("global_rules.md", "", StatusWarning, fmt.Sprintf("%d characters exceeds Windsurf's %d character limit for global rules", len(body), windsurfGlobalRulesLimit))})
		}
		return ops, ""
	}
	var files []ownedFile
	for _, r := range rules {
		trigger := "always_on"
		var fm []string
		switch {
		case len(r.Globs) > 0:
			trigger = "glob"
		case !r.Always && r.Description != "":
			trigger = "model_decision"
		case !r.Always:
			trigger = "manual"
		}
		fm = append(fm, "trigger: "+trigger)
		if r.Description != "" {
			fm = append(fm, "description: "+yamlScalar(r.Description))
		}
		if len(r.Globs) > 0 {
			fm = append(fm, "globs: "+yamlScalar(strings.Join(r.Globs, ",")))
		}
		files = append(files, ownedFile{r.Name, ownedMarkdown(fm, mdMarkerLine, r.Body)})
	}
	dir := filepath.Join(env.Project, ".windsurf", "rules")
	if dirExists(filepath.Join(env.Project, ".devin")) && !dirExists(filepath.Join(env.Project, ".windsurf")) {
		dir = filepath.Join(env.Project, ".devin", "rules")
	}
	return []Op{&ownedFilesOp{meta: m, dir: dir, ext: ".md", files: files, mode: 0o644}}, ""
}

func clineRules(env Env, scope Scope, rules []Rule) ([]Op, string) {
	dir := filepath.Join(env.Home, "Documents", "Cline", "Rules")
	if scope == ScopeProject {
		dir = filepath.Join(env.Project, ".clinerules")
		if fileExists(dir) {
			return nil, ".clinerules is a single file; convert it to a directory so relay can add rules beside yours"
		}
	}
	var files []ownedFile
	for _, r := range rules {
		var fm []string
		if len(r.Globs) > 0 {
			fm = append(fm, "paths:")
			for _, g := range r.Globs {
				fm = append(fm, "  - "+yamlScalar(g))
			}
		}
		files = append(files, ownedFile{r.Name, ownedMarkdown(fm, mdMarkerLine, r.Body)})
	}
	return []Op{&ownedFilesOp{meta: meta{Cline, KindRules, scope}, dir: dir, ext: ".md", files: files, mode: 0o644}}, ""
}
