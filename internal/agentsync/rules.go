package agentsync

import (
	"fmt"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"
)

const windsurfGlobalRulesLimit = 6000

func yamlScalar(s string) string {
	raw, err := yaml.Marshal(s)
	if err != nil {
		return `""`
	}
	return strings.TrimRight(string(raw), "\n")
}

func ownedMarkdown(frontmatter []string, markerLine, body string) []byte {
	var b strings.Builder
	if len(frontmatter) > 0 {
		b.WriteString("---\n" + strings.Join(frontmatter, "\n") + "\n---\n")
	}
	b.WriteString(markerLine + "\n\n" + strings.TrimSpace(body) + "\n")
	return []byte(b.String())
}

const mdMarkerLine = "<!-- " + Marker + ": generated by `relay sync`, edit the source in the relay sync directory -->"

// rulesBlock renders all rules as one managed block for agents that read a
// single instructions file.
func rulesBlock(rules []Rule) string {
	var parts []string
	for _, r := range rules {
		var b strings.Builder
		fmt.Fprintf(&b, "### %s\n", r.Name)
		if r.Description != "" {
			fmt.Fprintf(&b, "\n_%s_\n", r.Description)
		}
		if len(r.Globs) > 0 {
			fmt.Fprintf(&b, "\nApplies to files matching: %s\n", "`"+strings.Join(r.Globs, "`, `")+"`")
		}
		fmt.Fprintf(&b, "\n%s", strings.TrimSpace(r.Body))
		parts = append(parts, b.String())
	}
	return strings.Join(parts, "\n\n")
}

func blockRules(a AgentID, userPath, projectPath func(Env) string, noUser, noProject string) builder[Rule] {
	return func(env Env, scope Scope, rules []Rule) ([]Op, string) {
		path := ""
		switch {
		case scope == ScopeUser && noUser != "":
			return nil, noUser
		case scope == ScopeProject && noProject != "":
			return nil, noProject
		case scope == ScopeUser:
			path = userPath(env)
		default:
			path = projectPath(env)
		}
		return []Op{&mdBlockOp{meta: meta{a, KindRules, scope}, path: path, id: "rules", body: rulesBlock(rules)}}, ""
	}
}

func home(parts ...string) func(Env) string {
	return func(e Env) string { return filepath.Join(append([]string{e.Home}, parts...)...) }
}

func project(parts ...string) func(Env) string {
	return func(e Env) string { return filepath.Join(append([]string{e.Project}, parts...)...) }
}

